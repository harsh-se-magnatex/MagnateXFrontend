#!/usr/bin/env node
/**
 * Bundles legal markdown into TypeScript modules so pages never read the
 * filesystem at runtime (avoids Vercel output-file-tracing pulling in GBs).
 */

import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'content', 'legal');

const LEGAL_MARKDOWN_FILES = [
  'terms.md',
  'privacy.md',
  'acceptable-use.md',
  'ai-disclosure.md',
  'cookie.md',
  'refund.md',
  'sub-processors.md',
  'licenses.md',
];

function parseNotices(md) {
  const generatedMatch = md.match(/\*\*Generated:\*\*\s*([0-9-]+)/);
  const totalMatch = md.match(/\*\*Total third-party packages:\*\*\s*(\d+)/);

  const summary = [];
  const summaryBlock = md.split('## License summary')[1]?.split('## Packages by license')[0];
  if (summaryBlock) {
    const rows = summaryBlock
      .split('\n')
      .map((line) => line.trim())
      .filter(
        (line) =>
          line.startsWith('|') &&
          !line.includes('---') &&
          !/^\|\s*License\s*\|/i.test(line),
      );
    for (const row of rows) {
      const cells = row
        .split('|')
        .map((c) => c.trim())
        .filter(Boolean);
      if (cells.length >= 2) {
        const count = parseInt(cells[1], 10);
        if (!Number.isNaN(count)) {
          summary.push({ license: cells[0], count });
        }
      }
    }
  }

  const sections = [];
  const packagesBlock =
    md.split('## Packages by license')[1]?.split('## Notes')[0] ?? '';
  const sectionChunks = packagesBlock.split(/^###\s+/m).slice(1);
  for (const chunk of sectionChunks) {
    const headerMatch = chunk.match(/^([^\n]+)\n/);
    if (!headerMatch) continue;
    const header = headerMatch[1].trim();
    const headerInfo = header.match(/^(.*?)\s*\((\d+)\)$/);
    const license = headerInfo ? headerInfo[1].trim() : header;
    const count = headerInfo ? parseInt(headerInfo[2], 10) : 0;
    const entries = [];
    const lines = chunk.slice(headerMatch[0].length).split('\n');
    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed.startsWith('- ')) continue;
      const inner = trimmed.slice(2);
      const split = inner.split(/\s+—\s+/);
      const name = split[0].replace(/`/g, '').trim();
      const repository = split.slice(1).join(' — ').trim();
      entries.push({ name, repository });
    }
    sections.push({ license, count, entries });
  }

  return {
    generatedDate: generatedMatch?.[1] ?? null,
    total: totalMatch ? parseInt(totalMatch[1], 10) : null,
    summary,
    sections,
  };
}

function extractLicensesFooter(md) {
  const cleaned = md.replace(/<!--[\s\S]*?-->/g, '');
  const marker = '## Scope of this page';
  const start = cleaned.indexOf(marker);
  return start === -1 ? '' : cleaned.slice(start).trim();
}

mkdirSync(OUT_DIR, { recursive: true });

const documents = {};
for (const filename of LEGAL_MARKDOWN_FILES) {
  const filePath = join(ROOT, filename);
  if (!existsSync(filePath)) {
    console.warn(`⚠ Skipping missing legal file: ${filename}`);
    continue;
  }
  const key = filename.replace(/\.md$/, '');
  documents[key] = readFileSync(filePath, 'utf8');
}

const documentsTs = `// Auto-generated by scripts/bundle-legal-content.mjs — do not edit.

export const legalDocumentIds = ${JSON.stringify(Object.keys(documents))} as const;

export type LegalDocumentId = (typeof legalDocumentIds)[number];

export const legalDocuments: Record<LegalDocumentId, string> = ${JSON.stringify(documents, null, 2)};

export const licensesFooterMarkdown = ${JSON.stringify(
  extractLicensesFooter(documents.licenses ?? ''),
)};
`;

writeFileSync(join(OUT_DIR, 'documents.ts'), documentsTs);

const noticesPath = join(ROOT, 'THIRD_PARTY_NOTICES.md');
const noticesData = existsSync(noticesPath)
  ? parseNotices(readFileSync(noticesPath, 'utf8'))
  : { generatedDate: null, total: null, summary: [], sections: [] };

writeFileSync(
  join(OUT_DIR, 'licenses-notices.ts'),
  `// Auto-generated by scripts/bundle-legal-content.mjs — do not edit.

export type LicenseNoticeEntry = {
  name: string;
  repository: string;
};

export type LicenseNoticeSection = {
  license: string;
  count: number;
  entries: LicenseNoticeEntry[];
};

export const licensesNotices = ${JSON.stringify(noticesData, null, 2)} as {
  generatedDate: string | null;
  total: number | null;
  summary: { license: string; count: number }[];
  sections: LicenseNoticeSection[];
};
`,
);

console.log(
  `✓ Bundled ${Object.keys(documents).length} legal documents → content/legal/documents.ts`,
);
console.log('✓ Bundled THIRD_PARTY_NOTICES → content/legal/licenses-notices.ts');

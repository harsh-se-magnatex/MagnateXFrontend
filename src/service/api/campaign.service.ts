/** Firestore-typed shape returned from `GET /campaign/drafts`. */
export type CampaignDraft = {
  draftId: string;
  status: 'draft' | 'scheduled' | string;
  platform: string | null;
  message: string | null;
  imageUrl: string | null;
  imageFilePath: string | null;
  /** YYYY-MM-DD the campaign generator was targeting for this day. */
  targetDate: string | null;
  eventName: string | null;
  campaignTheme: string | null;
  campaignGoal: string | null;
  /** Shared across every draft from one campaign generation run. */
  parentJobId: string | null;
  /** Inclusive calendar window from the campaign builder anchor. */
  campaignWindowStart: string | null;
  campaignWindowEnd: string | null;
  /** Number of times this draft has been successfully regenerated.
   *  `0` => the next regen is FREE; anything `>= 1` => 1 credit. */
  regenerationCount: number;
  scheduledPostId: string | null;
  /** Firestore timestamp objects come back as `{ _seconds, _nanoseconds }`.
   *  Kept loosely-typed so the UI can format defensively. */
  scheduledAt: unknown;
  createdAt: unknown;
  /** True when this draft was produced by auto-mode campaign seed. */
  autoSeeded?: boolean;
  /** Soft-removed by the user — stays visible as "Removed by you". */
  userRemoved?: boolean;
};

export async function listCampaignDraftsApi(params?: {
  status?: 'draft' | 'scheduled';
  limit?: number;
}): Promise<CampaignDraft[]> {
  const response = await axiosClient.get<{
    success: boolean;
    data: { drafts: CampaignDraft[] };
    message?: string;
  }>('/api/v1/campaign/drafts', {
    params: {
      status: params?.status,
      limit: params?.limit,
    },
  });
  return response.data.data.drafts;
}

export type ScheduleCampaignDraftResponse = {
  draftId: string;
  scheduledPostId: string;
  scheduledAt: string;
};

export async function scheduleCampaignDraftApi(params: {
  draftId: string;
  /** ISO-8601 string. Server treats `<now` as an error. */
  scheduleAt: string;
}): Promise<ScheduleCampaignDraftResponse> {
  const response = await axiosClient.post<{
    success: boolean;
    data: ScheduleCampaignDraftResponse;
    message?: string;
  }>(`/api/v1/campaign/drafts/${encodeURIComponent(params.draftId)}/schedule`, {
    scheduleAt: params.scheduleAt,
  });
  return response.data.data;
}

export async function deleteCampaignDraftApi(params: {
  draftId: string;
}): Promise<{ draftId: string; userRemoved?: boolean }> {
  const response = await axiosClient.delete<{
    success: boolean;
    data: { draftId: string; userRemoved?: boolean };
    message?: string;
  }>(`/api/v1/campaign/drafts/${encodeURIComponent(params.draftId)}`);
  return response.data.data;
}

export type RegenerateCampaignDraftResponse = {
  accepted?: boolean;
  parentJobId?: string;
  draftId: string;
  /** Exact credit amount the worker will deduct on success. `0` for the
   *  user's free first regen. */
  chargeCredits: number;
  /** `regenerationCount` BEFORE this run — UI shows it for transparency. */
  regenerationCountBefore: number;
  successCount?: number;
  failedCount?: number;
  regeneratedDraftId?: string;
};

/**
 * Regenerate a single campaign draft synchronously (worker overwrites in place).
 *
 * Pricing: free for the first regen of any given draft, then 1 credit
 * for every regen after that. The exact charge for THIS attempt is in
 * `chargeCredits` on the response.
 */
export async function regenerateCampaignDraftApi(params: {
  draftId: string;
}): Promise<RegenerateCampaignDraftResponse> {
  const response = await axiosClient.post<{
    success: boolean;
    data: RegenerateCampaignDraftResponse;
    message?: string;
  }>(
    `/api/v1/campaign/drafts/${encodeURIComponent(params.draftId)}/regenerate`,
    {}
  );
  return response.data.data;
}

/**
 * Convenience helper: the dollar-cost of the NEXT regen for a draft. Free
 * on the first attempt (`regenerationCount === 0`), `CAMPAIGN_REGENERATE_CREDIT`
 * on the second (`=== 1`). No further regens after that.
 */
export function canRegenerateDraft(regenerationCount: number): boolean {
  const count =
    typeof regenerationCount === 'number' && Number.isFinite(regenerationCount)
      ? Math.max(0, Math.floor(regenerationCount))
      : 0;
  return count < MAX_CAMPAIGN_REGENERATIONS;
}

export function nextRegenerationCost(regenerationCount: number): number {
  const count =
    typeof regenerationCount === 'number' && Number.isFinite(regenerationCount)
      ? Math.max(0, Math.floor(regenerationCount))
      : 0;
  return count === 1 ? CAMPAIGN_REGENERATE_CREDIT : 0;
}

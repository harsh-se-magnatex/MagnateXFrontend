export type CreateCampaignDayInput = {
  /** YYYY-MM-DD in the caller's timezone — server validates against the
   *  user's account timezone before enqueueing. */
  date: string;
  title: string;
  reference: string;
  caption?: string;
  dayNumber?: number;
};

export type CreateCampaignParams = {
  theme: string;
  description?: string;
  goal?: string;
  days: CreateCampaignDayInput[];
  /** Inclusive builder window (`YYYY-MM-DD`) — wider than drafted day dates. */
  windowStart?: string;
  windowEnd?: string;
  /** Optional explicit platform list. When omitted the server uses the
   *  caller's `selected` accounts (same default as festive-post). */
  platforms?: string[];
  /** Optional reference to the saved suggestion that seeded this campaign —
   *  helps server-side analytics tie drafts back to a card. */
  suggestionId?: string;
};

/** Response from `POST /api/v1/campaign/create` (queued to Cloud Tasks). */
export type CreateCampaignResponse = {
  accepted?: boolean;
  parentJobId?: string;
  successCount: number;
  failedCount: number;
  dayCount: number;
  platforms: string[];
  /** Total credits charged when every (day × platform) succeeds. */
  requiredCredits: number;
  /** Number of draft docs expected for this enqueue (platform × day). */
  expectedDraftCount?: number;
};

export async function createCampaignApi(
  params: CreateCampaignParams
): Promise<CreateCampaignResponse> {
  const response = await axiosClient.post<{
    success: boolean;
    data: CreateCampaignResponse;
    message?: string;
  }>('/api/v1/campaign/create', {
    theme: params.theme,
    description: params.description,
    goal: params.goal,
    days: params.days,
    windowStart: params.windowStart,
    windowEnd: params.windowEnd,
    platforms: params.platforms,
    suggestionId: params.suggestionId,
  });
  return response.data.data;
}


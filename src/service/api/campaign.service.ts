import axiosClient from '@/lib/axios';

/** Hard cap on how many days a single campaign can plan. Mirrors the
 *  backend constant so the two layers can never drift. Used for the
 *  date-picker window; AI idea length defaults to {@link DEFAULT_CAMPAIGN_PLAN_DAYS}. */
export const MAX_CAMPAIGN_DAYS = 7;
/** Default AI campaign idea length (manual + auto-mode). */
export const DEFAULT_CAMPAIGN_PLAN_DAYS = 5;
/** Default suggestion-set size when the page first loads. */
export const DEFAULT_CAMPAIGN_SET_SIZE = 5;
/** Credit cost per (day × platform) — mirrors backend
 *  `CAMPAIGN_CREDIT_PER_DAY`. Update both in lockstep. */
export const CAMPAIGN_CREDIT_PER_DAY = 3;
/** Credit cost per paid regeneration. Mirrors backend
 *  `CAMPAIGN_REGENERATE_CREDIT`. Max 2 regens per draft: 1st free, 2nd paid. */
export const CAMPAIGN_REGENERATE_CREDIT = 1;
export const MAX_CAMPAIGN_REGENERATIONS = 2;

export type CampaignDayPlan = {
  dayNumber: number;
  title: string;
  reference: string;
  caption?: string;
};

export type CampaignSuggestion = {
  id: string;
  theme: string;
  description: string;
  goal?: string;
  generatedAt: string;
  days: CampaignDayPlan[];
};

export type CampaignSuggestionSet = {
  suggestions: CampaignSuggestion[];
  /** Server-clamped max days for THIS user (capped by plan window + 5-day
   *  campaign plan default). When null, the saved set predates this field —
   *  treat as the default 5-day plan length. */
  maxDays: number | null;
  /** Goal the set was generated against. Null when the user did not supply
   *  one. */
  goal: string | null;
  /** `true` when this set was generated by the auto-mode campaign seed
   *  (NOT the user clicking "Generate ideas"). Drives the
   *  "AI picked this idea for you" badge + reason on the UI. */
  autoSeeded?: boolean;
  /** When `autoSeeded`, the id of the suggestion the auto-mode picker
   *  selected to actually run. Always present alongside `autoSeeded`. */
  pickedSuggestionId?: string | null;
  /** 1\u20132 sentence justification the picker returned. Surfaced verbatim
   *  beneath the picked card. */
  pickedReason?: string | null;
};

// -----------------------------------------------------------------------------
// Suggestion lifecycle
// -----------------------------------------------------------------------------

/**
 * Generate a fresh set of N campaign suggestions. The backend clamps `count`
 * to `[1..5]` and sizes `maxDays` to the user's remaining plan window.
 */
export async function suggestCampaignSetApi(params: {
  goal?: string;
  count?: number;
}): Promise<CampaignSuggestionSet> {
  const response = await axiosClient.post<{
    success: boolean;
    data: CampaignSuggestionSet;
    message?: string;
  }>('/api/v1/campaign/suggest-set', {
    goal: params.goal?.trim() || undefined,
    count: params.count,
  });
  return response.data.data;
}

/**
 * Fetch the user's currently-saved suggestion set. Returns an empty
 * `{ suggestions: [] }` envelope when there's nothing saved yet.
 */
export async function getCampaignSuggestionsApi(): Promise<CampaignSuggestionSet> {
  const response = await axiosClient.get<{
    success: boolean;
    data: CampaignSuggestionSet;
    message?: string;
  }>('/api/v1/campaign/suggestions');
  return response.data.data;
}

/**
 * Regenerate ONE card in the saved suggestion set. Returns the replacement
 * suggestion (same `id` as the one it replaced, fresh `generatedAt`).
 */
export async function regenerateCampaignApi(
  suggestionId: string
): Promise<CampaignSuggestion> {
  const response = await axiosClient.post<{
    success: boolean;
    data: { suggestion: CampaignSuggestion };
    message?: string;
  }>('/api/v1/campaign/regenerate', { suggestionId });
  return response.data.data.suggestion;
}

